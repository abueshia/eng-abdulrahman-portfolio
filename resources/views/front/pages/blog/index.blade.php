    var articlesData = @json($articles);
    var baseUrl = "{{ asset('') }}";
    
    function openArticleModal(id) {
        var article = articlesData.find(a => a.id === id);
        if (article) {
            document.getElementById('modalImg').src = baseUrl + article.img;
            document.getElementById('modalTitle').textContent = article.title;
            document.getElementById('modalContent').innerHTML = '<p>' + article.intro + '</p><h3>التفاصيل الطبية</h3><p>' + article.body + '</p><br><strong>للمزيد من الاستشارات والحصول على التشخيص الدقيق، يمكنك حجز موعد معنا في العيادة.</strong>';
